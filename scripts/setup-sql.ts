// Builds supabase/setup.sql: every migration in supabase/migrations, oldest
// first, in one script you can paste into the Supabase SQL Editor and run as
// often as you like.
//
// Each migration runs once. Applied ones are recorded in
// supabase_migrations.schema_migrations, the same table `supabase db push`
// and the GitHub integration use, so switching to either later won't re-run
// them. The whole script is one transaction: if anything fails, nothing
// changes.
//
//   bun scripts/setup-sql.ts           rewrite supabase/setup.sql
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
export const MIGRATIONS_DIR = path.join(ROOT, "supabase/migrations");
export const SETUP_SQL = path.join(ROOT, "supabase/setup.sql");

const BODY_TAG = "$lotpulse_migration$";

const HEADER = `-- LotPulse: one-shot database setup. GENERATED by scripts/setup-sql.ts from
-- supabase/migrations. Don't edit by hand; add a migration and regenerate.
--
-- Paste the whole file into Supabase → SQL Editor → New query and press Run.
-- Safe to run again: migrations already applied are skipped. It runs as one
-- transaction, so a failure changes nothing.

begin;

-- Migration history, shared with the Supabase CLI and GitHub integration.
create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations (
  version text primary key,
  statements text[],
  name text
);

-- Databases set up by hand before this script existed: record what's there.
do $baseline$
begin
  if to_regclass('public.reports') is not null then
    insert into supabase_migrations.schema_migrations (version, name) values
      ('20261008000000', 'live_sightings'),
      ('20261009000000', 'launch_hardening'),
      ('20261011000000', 'reports')
    on conflict (version) do nothing;
  elsif to_regclass('public.sightings') is not null then
    insert into supabase_migrations.schema_migrations (version, name)
    values ('20261008000000', 'live_sightings')
    on conflict (version) do nothing;
    if exists (
      select 1 from pg_policies
      where schemaname = 'public' and tablename = 'sightings'
        and policyname = 'Recent sightings are public'
    ) then
      insert into supabase_migrations.schema_migrations (version, name)
      values ('20261009000000', 'launch_hardening')
      on conflict (version) do nothing;
    end if;
  end if;
end
$baseline$;
`;

const FOOTER = `
-- Live updates: make sure every new report is broadcast over Realtime.
do $realtime$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
    and not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'reports'
    )
  then
    alter publication supabase_realtime add table public.reports;
  end if;
end
$realtime$;

-- Let the API see the new tables and functions straight away.
notify pgrst, 'reload schema';

commit;

-- Result: every migration listed, and reports_in_realtime = true.
select
  (select string_agg(version, ', ' order by version) from supabase_migrations.schema_migrations)
    as applied_migrations,
  exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'reports'
  ) as reports_in_realtime;
`;

export function buildSetupSql(): string {
  const files = readdirSync(MIGRATIONS_DIR)
    .filter((file) => file.endsWith(".sql"))
    .sort();
  const steps = files.map((file) => {
    const match = /^(\d+)_(.+)\.sql$/.exec(file);
    if (!match) throw new Error(`Unexpected migration file name: ${file}`);
    const [, version, name] = match;
    const sql = readFileSync(path.join(MIGRATIONS_DIR, file), "utf8").trim();
    if (sql.includes(BODY_TAG)) throw new Error(`${file} contains ${BODY_TAG}`);
    return `
-- ${file} ${"-".repeat(Math.max(0, 76 - file.length))}
do $step$
begin
  if not exists (
    select 1 from supabase_migrations.schema_migrations where version = '${version}'
  ) then
    execute ${BODY_TAG}
${sql}
${BODY_TAG};
    insert into supabase_migrations.schema_migrations (version, name)
    values ('${version}', '${name}');
  end if;
end
$step$;
`;
  });
  return HEADER + steps.join("") + FOOTER;
}

if (import.meta.main) {
  writeFileSync(SETUP_SQL, buildSetupSql());
  console.log(`Wrote ${path.relative(process.cwd(), SETUP_SQL)}`);
}
